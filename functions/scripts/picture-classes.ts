/**
 * Builds the class table of the picture search's entity step (`src/pictureClassTable.ts`): for each kind of
 * list, every Wikidata class under its root classes (`wdt:P279*`), so the server tells a film from a dish
 * by Wikidata's own ids without asking anything at search time. Run about once a month, then commit:
 *
 *   npm run picture-classes
 *
 * Read-only: it asks query.wikidata.org and writes the one file.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { USER_AGENT } from "../src/pictureSources";

/** The root classes of each kind. Changing them is changing what the search counts as that kind. */
export const ROOTS: Record<string, readonly string[]> = {
  // film, film series
  film: ["Q11424", "Q24856"],
  // television series, television program, miniseries
  tv: ["Q5398426", "Q15416", "Q1259759"],
  // anime television series, anime film, original video animation
  anime: ["Q63952888", "Q20650540", "Q220898"],
  // manga, manga series
  manga: ["Q8274", "Q21198342"],
  // video game, video game series
  games: ["Q7889", "Q7058673"],
  // literary work, book, book series, novel series, comics, comic book series
  books: ["Q7725634", "Q571", "Q277759", "Q1667921", "Q1004", "Q14406742"],
  // musical group
  musicGroup: ["Q215380"],
  // album, single, song, musical work
  musicWork: ["Q482994", "Q134556", "Q7366", "Q105543609"],
  // taxon, breed
  animals: ["Q16521", "Q38829"],
  // food, dish, drink
  food: ["Q2095", "Q746549", "Q40050"],
  // sports club, sports team
  sport: ["Q847017", "Q12973014"],
  // automobile model, motor car, automobile manufacturer, motorcycle model
  cars: ["Q3231690", "Q1420", "Q786820", "Q23866334"],
  // brand, business, trademark
  brands: ["Q431289", "Q4830453", "Q167270"],
  // occupations: musician, singer, rapper (a person in a music list)
  musicianJob: ["Q639669", "Q177220", "Q2252262"],
  // occupations: athlete (a person in a sport list)
  athleteJob: ["Q2066131"],
  // never what somebody means: disambiguation page, family name, given name, Wikimedia list, category, template, name
  notAThing: ["Q4167410", "Q101352", "Q202444", "Q13406463", "Q4167836", "Q11266439", "Q82799"],
};

const pause = (ms: number) => new Promise((done) => setTimeout(done, ms));

async function subclasses(root: string): Promise<number[]> {
  const query = `SELECT ?c WHERE { ?c wdt:P279* wd:${root} }`;
  for (let attempt = 1; ; attempt++) {
    const reply = await fetch(`https://query.wikidata.org/sparql?format=json&query=${encodeURIComponent(query)}`, {
      headers: { "User-Agent": USER_AGENT, Accept: "application/sparql-results+json" },
      signal: AbortSignal.timeout(90_000),
    }).catch((error: unknown) => error as Error);
    if (!(reply instanceof Error) && reply.ok) {
      const body = (await reply.json()) as { results: { bindings: { c: { value: string } }[] } };
      return body.results.bindings.flatMap(({ c }) => {
        const id = /\/Q(\d+)$/.exec(c.value)?.[1];
        return id ? [Number(id)] : [];
      });
    }
    const why = reply instanceof Error ? reply.message : String(reply.status);
    if (attempt >= 4) throw new Error(`${root}: ${why}`);
    console.log(`  ${root}: ${why}, again in ${20 * attempt} s`);
    await pause(20_000 * attempt);
  }
}

async function main(): Promise<void> {
  const table: Record<string, string> = {};
  for (const [kind, roots] of Object.entries(ROOTS)) {
    const ids = new Set<number>();
    for (const root of roots) {
      const found = await subclasses(root);
      found.forEach((id) => ids.add(id));
      console.log(`${kind} ${root}: ${found.length}`);
      await pause(2_000);
    }
    table[kind] = [...ids].sort((a, b) => a - b).map((id) => id.toString(36)).join(",");
    console.log(`${kind}: ${ids.size} classes`);
  }
  const day = new Date().toISOString().slice(0, 10);
  const lines = [
    `// Generated by \`npm run picture-classes\` (scripts/picture-classes.ts) on ${day}. Do not edit by hand.`,
    "// Each kind's Wikidata classes, the numbers of their Q-ids in base 36, ascending.",
    `export const CLASS_TABLE_DATE = "${day}";`,
    "export const CLASS_TABLE: Readonly<Record<string, string>> = {",
    ...Object.entries(table).map(([kind, ids]) => `  ${kind}: "${ids}",`),
    "};",
    "",
  ];
  writeFileSync(join(__dirname, "..", "..", "src", "pictureClassTable.ts"), lines.join("\n"));
}

void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
